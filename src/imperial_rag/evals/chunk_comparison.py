DEFAULT_CONFIGS = [(400, 50), *((size, size * percent // 100)
                                for size in (256, 512, 1024) for percent in (0, 10, 20))]


def write_json(path: Path, payload: Any) -> None:
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def shadow_settings(settings: Settings, run_id: str, root: Path) -> Settings:
    # The name is generated by this runner, never an active target supplied by an operator.
    return settings.model_copy(update={
        "shadow_run_id": run_id, "extraction_root_override": root / "extracted",
        "manifest_db_path_override": root / "manifest.sqlite3",
        "elasticsearch_index": f"imperial_eval__shadow__{run_id}",
        "qdrant_collection": f"imperial_eval__shadow__{run_id}",
    })


def build_shadow_retriever(
    snapshot: dict[str, Any], settings: Settings, retrieval: RetrievalSettings,
) -> Any:
    from imperial_rag.indexing.vector import create_qdrant_vector_store, index_vector_documents
    from imperial_rag.retrieval.elasticsearch import ElasticsearchKeywordIndex
    from imperial_rag.retrieval.service import RetrievalService
    from qdrant_client import QdrantClient

    documents = [Document(page_content=row["page_content"], metadata=row["metadata"])
                 for row in snapshot["sources"]]
    chunks = build_chunks(documents, retrieval.chunk_size, retrieval.chunk_overlap)
    keywords = ElasticsearchKeywordIndex(settings)
    qdrant = QdrantClient(url=settings.qdrant_url)
    try:
        if keywords.client.indices.exists(index=settings.elasticsearch_index) or qdrant.collection_exists(settings.qdrant_collection):
            raise ValueError("Shadow target already exists; refusing to modify it")
    finally:
        qdrant.close()
    settings.extraction_root.mkdir(parents=True, exist_ok=False)
    write_jsonl(settings.extraction_root / "chunks.jsonl", [document_payload(doc) for doc in chunks])
    store = create_qdrant_vector_store(settings)
    try:
        keywords.index_documents(chunks)
        ids = index_vector_documents(chunks, settings=settings, vector_store=store)
        if len(ids) != len(chunks):
            raise ValueError("Incomplete shadow vector indexing")
        if int(keywords.client.count(index=settings.elasticsearch_index)["count"]) != len(chunks):
            raise ValueError("Incomplete shadow keyword indexing")
        if store.client.count(collection_name=settings.qdrant_collection, exact=True).count != len(chunks):
            raise ValueError("Shadow vector count mismatch")
    except Exception:
        keywords.client.close()
        store.client.close()
        raise
    vector = store.as_retriever(search_type="mmr", search_kwargs={
        "k": retrieval.vector_k, "fetch_k": retrieval.vector_fetch_k,
        "lambda_mult": retrieval.mmr_lambda_mult,
    })
    service = RetrievalService(vector, keywords, retrieval)
    return service, (keywords.client, store.client)


async def evaluate_configuration(
    examples: list[dict[str, Any]], snapshot: dict[str, Any], service: Any, *, concurrency: int = 3,
    ranking_corpus: EvidenceRankingCorpus | None = None,
) -> list[dict[str, Any]]:
    if concurrency < 1:
        raise ValueError("Concurrency must be positive")
    semaphore = asyncio.Semaphore(concurrency)

    async def evaluate(example: dict[str, Any]) -> dict[str, Any]:
        async with semaphore:
            started = time.perf_counter()
            row: dict[str, Any] = {"id": example["id"], "split": example["split"],
                                   "eligible": False, "documents": []}
            try:
                result = await asyncio.to_thread(service.retrieve, example["question"].strip())
                row["retrieval"] = result.diagnostics
                row["documents"] = [document_payload(doc) for doc in result.evidence]
                row["retrieved_chunk_ids"] = [doc.metadata.get("chunk_id") for doc in result.evidence]
                row["retrieved_source_spans"] = [span for doc in result.evidence
                                                  for span in doc.metadata.get("source_spans", [])]
                row["metrics"] = await asyncio.to_thread(
                    score_retrieval, example, result.evidence, snapshot, ranking_corpus=ranking_corpus,
                )
                degraded = bool(result.diagnostics.get("fallbacks") or result.diagnostics.get("degraded"))
                row["eligible"] = not degraded
                if degraded:
                    row["error"] = "degraded_retrieval"
            except Exception as exc:
                # Provider exception strings may contain credentials or corpus text.
                row["error"] = type(exc).__name__
            row["latency_ms"] = (time.perf_counter() - started) * 1000
            return row

    return list(await asyncio.gather(*(evaluate(example) for example in examples)))


def summarize(rows: list[dict[str, Any]], *, include_ranking: bool = False) -> dict[str, Any]:
    valid = [row for row in rows if row["eligible"]]
    result: dict[str, Any] = {"eligible": bool(rows) and len(valid) == len(rows),
                              "questions": len(rows), "errors": len(rows) - len(valid), "budgets": {}}
    for k in KS:
        for metric in ("evidence_recall", "full_evidence_success"):
            key = f"{metric}_at_{k}"
            values = [row["metrics"][key] for row in valid if row["metrics"][key] is not None]
            result[key] = mean(values) if values else None
    for budget in BUDGETS:
        metrics = [row["metrics"]["budgets"][str(budget)] for row in valid]
        result["budgets"][str(budget)] = {
            key: mean(values) if (values := [entry[key] for entry in metrics if entry[key] is not None]) else None
            for key in ("evidence_recall", "full_evidence_success", "proxy_tokens", "budget_utilization")
        }
    result["mean_latency_ms"] = mean(row["latency_ms"] for row in rows) if rows else None
    if include_ranking or any("ranking_metric_version" in row.get("metrics", {}) for row in rows):
        ranked = [row["metrics"] for row in valid if row["metrics"].get("ranking_metric_version") == RANKING_VERSION
                  and row["metrics"]["relevant_chunk_count"] is not None]
        result["ranking_questions"] = len(ranked)
        result["zero_relevant_questions"] = sum(row["relevant_chunk_count"] == 0 for row in ranked)
        for k in KS:
            for per_query, aggregate in (("rr", "mrr"), ("ap", "map"), ("ndcg", "ndcg")):
                result[f"evidence_{aggregate}_at_{k}"] = (
                    mean(row[f"evidence_{per_query}_at_{k}"] for row in ranked) if ranked else None
                )
    return result


def rank_configurations(summaries: list[dict[str, Any]]) -> list[str]:
    valid = [row for row in summaries if row["eligible"]
             and row["budgets"]["2000"]["evidence_recall"] is not None]
    return [row["config_id"] for row in sorted(valid, key=lambda row: (
        -row["budgets"]["2000"]["evidence_recall"],
        -row["budgets"]["2000"]["full_evidence_success"],
        row["budgets"]["2000"]["proxy_tokens"], row["config_id"],
    ))]


async def run_comparison(
    snapshot: dict[str, Any], benchmark: dict[str, Any], settings: Settings, output: Path,
    *, configs: list[tuple[int, int]] | None = None, concurrency: int = 3, split: str = "dev",
) -> dict[str, Any]:
    from imperial_rag.integrations.dashscope import QwenProviderSettings

    resolved = DEFAULT_CONFIGS if configs is None else configs
    if not resolved or len(set(resolved)) != len(resolved) or any(
        type(size) is not int or type(overlap) is not int or not 0 <= overlap < size for size, overlap in resolved
    ):
        raise ValueError("Configuration matrix requires unique positive sizes and 0 <= overlap < size")
    if concurrency < 1 or split not in {"dev", "test"}:
        raise ValueError("Invalid concurrency or split")
    examples = [row for row in benchmark["examples"] if row["split"] == split]
    if not examples or benchmark["snapshot_hash"] != snapshot["snapshot_hash"]:
        raise ValueError("Empty split or benchmark snapshot mismatch")
    provider = QwenProviderSettings.from_env()
    provider.require_api_key()
    retrieval = replace(RetrievalSettings.from_env(), rerank_top_n=100)
    output.mkdir(parents=True, exist_ok=False)
    run_id = uuid.uuid4().hex
    manifest: dict[str, Any] = {
        "schema_version": "imperial-chunk-comparison-v1", "run_id": run_id,
        "snapshot_hash": snapshot["snapshot_hash"], "dataset_hash": benchmark["dataset_hash"],
        "split": split, "tokenizer": "cl100k_base", "tiktoken_version": version("tiktoken"),
        "chunk_size_unit": "estimated_token_count-v1", "retrieval_settings": retrieval.to_dict(),
        "embedding": provider.vector_metadata().to_dict(), "chat_model": provider.chat_model,
        "rerank_model": provider.rerank_model, "configs": [],
        "evaluator_version": "source-evidence-v1",
        "ranking_metric_version": RANKING_VERSION,
        "package_versions": {name: version(name) for name in ("langchain-text-splitters", "arize-phoenix-client")},
    }
    if "phoenix_dataset" in benchmark:
        manifest["phoenix_dataset"] = benchmark["phoenix_dataset"]
    write_json(output / "benchmark.json", benchmark)
    summaries = []
    for size, overlap in resolved:
        config_id = f"s{size}-o{overlap}"
        root = output / config_id
        root.mkdir()
        target = shadow_settings(settings, f"{run_id}_{config_id}", root)
        config = {"config_id": config_id, "chunk_size": size, "chunk_overlap": overlap,
                  "keyword_index": target.elasticsearch_index, "qdrant_collection": target.qdrant_collection}
        manifest["configs"].append(config)
        write_json(output / "manifest.json", manifest)
        resources: tuple[Any, ...] = ()
        try:
            service, resources = await asyncio.to_thread(
                build_shadow_retriever, snapshot, target, replace(retrieval, chunk_size=size, chunk_overlap=overlap),
            )
            corpus = await asyncio.to_thread(load_ranking_corpus, target.extraction_root / "chunks.jsonl",
                                             snapshot, examples)
            config["ranking_corpus_hash"] = corpus.corpus_hash
            rows = await evaluate_configuration(examples, snapshot, service, concurrency=concurrency,
                                                ranking_corpus=corpus)
        except Exception as exc:
            rows = [{"id": row["id"], "split": split, "eligible": False, "error": type(exc).__name__,
                     "documents": [], "latency_ms": 0} for row in examples]
        finally:
            for resource in resources:
                await asyncio.to_thread(resource.close)
        for row in rows:
            if "phoenix_dataset" in manifest:
                row["phoenix_dataset"] = manifest["phoenix_dataset"]
            row.update({"config_id": config_id, "snapshot_hash": snapshot["snapshot_hash"],
                        "dataset_hash": benchmark["dataset_hash"]})
        write_jsonl(root / "results.jsonl", rows)
        summary = summarize(rows, include_ranking=True) | config
        summaries.append(summary)
        write_json(output / "summary.json", {"configurations": summaries,
                   "ranking": rank_configurations(summaries) if split == "dev" else []})
    manifest["results_hash"] = digest([read_jsonl(output / row["config_id"] / "results.jsonl") for row in summaries])
    manifest["eligible"] = all(row["eligible"] for row in summaries)
    write_json(output / "manifest.json", manifest)
    return manifest


def load_comparison(root: Path) -> tuple[dict[str, Any], dict[str, Any], list[dict[str, Any]]]:
    manifest = json.loads((root / "manifest.json").read_text())
    benchmark = json.loads((root / "benchmark.json").read_text())
    if any(not re.fullmatch(r"s[1-9][0-9]*-o[0-9]+", config["config_id"]) for config in manifest["configs"]):
        raise ValueError("Invalid configuration ID in comparison manifest")
    if digest({key: value for key, value in benchmark.items() if key != "dataset_hash"}) != manifest["dataset_hash"]:
        raise ValueError("Comparison benchmark changed")
    if manifest.get("phoenix_dataset") != benchmark.get("phoenix_dataset"):
        raise ValueError("Comparison Phoenix dataset binding changed")
    results = [read_jsonl(root / config["config_id"] / "results.jsonl") for config in manifest["configs"]]
    if digest(results) != manifest.get("results_hash"):
        raise ValueError("Incomplete or modified comparison results")
    if manifest.get("ranking_metric_version") is not None:
        if manifest["ranking_metric_version"] != RANKING_VERSION:
            raise ValueError("Unsupported ranking metric version")
        for config, rows in zip(manifest["configs"], results):
            for row in rows:
                if row["eligible"] and (
                    not config.get("ranking_corpus_hash")
                    or row["metrics"].get("ranking_metric_version") != RANKING_VERSION
                    or row["metrics"].get("ranking_corpus_hash") != config.get("ranking_corpus_hash")
                ):
                    raise ValueError("Comparison ranking corpus or metric version changed")
    return manifest, benchmark, [row for rows in results for row in rows]


async def generate_comparison_answers(root: Path, *, concurrency: int = 3) -> list[dict[str, Any]]:
    from imperial_rag.answering.workflow import build_query_workflow
    from imperial_rag.evals.phoenix_experiment import citation_behavior, source_hint_behavior
    from imperial_rag.integrations.dashscope import QwenProviderSettings, create_chat_model

    if concurrency < 1:
        raise ValueError("Concurrency must be positive")
    manifest, benchmark, results = load_comparison(root)
    if manifest["split"] != "dev":
        raise ValueError("Automatic shortlist selection uses development data only")
    groups = {config["config_id"]: [row for row in results if row["config_id"] == config["config_id"]]
              for config in manifest["configs"]}
    ranking = rank_configurations([summarize(rows) | {"config_id": key} for key, rows in groups.items()])
    selected = set(["s400-o50", *[key for key in ranking if key != "s400-o50"][:2]])
    if "s400-o50" not in ranking:
        raise ValueError("A successful baseline run is required for answer comparison")
    if QwenProviderSettings.from_env().chat_model != manifest["chat_model"]:
        raise ValueError("Chat model changed since the comparison manifest was recorded")
    destination = root / "answers.jsonl"
    if destination.exists():
        raise FileExistsError(destination)
    examples = {row["id"]: row for row in benchmark["examples"]}
    semaphore = asyncio.Semaphore(concurrency)
    model = create_chat_model()

    async def generate(row: dict[str, Any]) -> dict[str, Any]:
        async with semaphore:
            example = examples[row["id"]]
            docs = [Document(**document) for document in row["documents"]]
            packed = await asyncio.to_thread(pack_context, docs, 2000)
            result: dict[str, Any] = {"id": row["id"], "config_id": row["config_id"],
                                      "question": example["question"], "reference_answer": example["reference_answer"],
                                      "review_status": "pending", "proxy_tokens": packed["proxy_tokens"],
                                      "context": packed["context"], "dataset_hash": manifest["dataset_hash"]}
            if "phoenix_dataset" in manifest:
                result["phoenix_dataset"] = manifest["phoenix_dataset"]
            try:
                workflow = build_query_workflow(retrieve=lambda _: docs, chat_model=model, context_token_budget=2000)
                answer = await asyncio.to_thread(workflow.invoke, {"question": example["question"]})
                output = {"answer": answer["answer"], "citations": answer.get("citations", []),
                          "documents": [document_payload(doc) for doc in packed["documents"]]}
                result.update(output)
                result["checks"] = {
                    "citation_behavior": citation_behavior(example, output, example),
                    "source_hint_behavior": source_hint_behavior(example, output, example),
                    "citations_valid": answer.get("citations_valid"),
                    "cited_evidence": evidence_recall(example["evidence"], answer.get("cited_documents", [])),
                }
            except Exception as exc:
                result["error"] = type(exc).__name__
            return result

    answers = list(await asyncio.gather(*(generate(row) for row in results if row["config_id"] in selected)))
    write_jsonl(destination, answers)
    return answers
